SELECT da.TENDEAN,
       CAST(COALESCE(SUM(pc.THOIGIAN), 0) AS DECIMAL(18, 2)) AS TONG_GIO_DECIMAL_CAST,
       CONVERT(DECIMAL(18, 2), COALESCE(SUM(pc.THOIGIAN), 0)) AS TONG_GIO_DECIMAL_CONVERT,
       CAST(CAST(COALESCE(SUM(pc.THOIGIAN), 0) AS DECIMAL(18, 2)) AS VARCHAR(30)) AS TONG_GIO_VARCHAR_CAST,
       CONVERT(VARCHAR(30), CONVERT(DECIMAL(18, 2), COALESCE(SUM(pc.THOIGIAN), 0))) AS TONG_GIO_VARCHAR_CONVERT
FROM dbo.DEAN AS da
LEFT JOIN dbo.PHANCONG AS pc ON pc.MADA = da.MADA
GROUP BY da.MADA, da.TENDEAN
ORDER BY da.MADA;

SELECT pb.TENPHG,
       CAST(AVG(nv.LUONG) AS DECIMAL(18, 2)) AS LUONG_TB_DECIMAL_CAST,
       CONVERT(DECIMAL(18, 2), AVG(nv.LUONG)) AS LUONG_TB_DECIMAL_CONVERT,
       REPLACE(CAST(CAST(AVG(nv.LUONG) AS DECIMAL(18, 2)) AS VARCHAR(30)), '.', ',') AS LUONG_TB_DAU_PHAY_CAST,
       REPLACE(CONVERT(VARCHAR(30), CONVERT(DECIMAL(18, 2), AVG(nv.LUONG))), '.', ',') AS LUONG_TB_DAU_PHAY_CONVERT
FROM dbo.PHONGBAN AS pb
LEFT JOIN dbo.NHANVIEN AS nv ON nv.PHG = pb.MAPHG
GROUP BY pb.MAPHG, pb.TENPHG
ORDER BY pb.MAPHG;

SELECT pb.TENPHG,
       CAST(FORMAT(CAST(AVG(nv.LUONG) AS DECIMAL(18, 2)), N'#,##0.00', N'en-US') AS VARCHAR(40)) AS LUONG_TB_VARCHAR_CAST,
       CONVERT(VARCHAR(40), CONVERT(MONEY, AVG(nv.LUONG)), 1) AS LUONG_TB_VARCHAR_CONVERT
FROM dbo.PHONGBAN AS pb
LEFT JOIN dbo.NHANVIEN AS nv ON nv.PHG = pb.MAPHG
GROUP BY pb.MAPHG, pb.TENPHG
ORDER BY pb.MAPHG;

SELECT da.TENDEAN,
       CEILING(COALESCE(SUM(pc.THOIGIAN), 0)) AS TONG_GIO_CEILING,
       FLOOR(COALESCE(SUM(pc.THOIGIAN), 0)) AS TONG_GIO_FLOOR,
       CAST(ROUND(COALESCE(SUM(pc.THOIGIAN), 0), 2) AS DECIMAL(18, 2)) AS TONG_GIO_LAM_TRON
FROM dbo.DEAN AS da
LEFT JOIN dbo.PHANCONG AS pc ON pc.MADA = da.MADA
GROUP BY da.MADA, da.TENDEAN
ORDER BY da.MADA;

DECLARE @TenPhong NVARCHAR(15) = N'Nghiên cứu';
DECLARE @LuongTrungBinh DECIMAL(18, 2);

SELECT @LuongTrungBinh = CAST(ROUND(AVG(nv.LUONG), 2) AS DECIMAL(18, 2))
FROM dbo.NHANVIEN AS nv
INNER JOIN dbo.PHONGBAN AS pb ON pb.MAPHG = nv.PHG
WHERE pb.TENPHG = @TenPhong;

SELECT HONV, TENLOT, TENNV
FROM dbo.NHANVIEN
WHERE LUONG > @LuongTrungBinh
ORDER BY MANV;

SELECT UPPER(nv.HONV) AS HONV,
       LOWER(nv.TENLOT) AS TENLOT,
       STUFF(LOWER(nv.TENNV), 2, 1, UPPER(SUBSTRING(nv.TENNV, 2, 1))) AS TENNV,
       LTRIM(RTRIM(SUBSTRING(dc.DIA_CHI, vt.VI_TRI_DAU_CACH + 1,
           CASE WHEN vt.VI_TRI_DAU_PHAY > vt.VI_TRI_DAU_CACH
                THEN vt.VI_TRI_DAU_PHAY - vt.VI_TRI_DAU_CACH - 1
                ELSE LEN(dc.DIA_CHI) - vt.VI_TRI_DAU_CACH END))) AS DCHI
FROM dbo.NHANVIEN AS nv
CROSS APPLY (SELECT LTRIM(RTRIM(nv.DCHI)) AS DIA_CHI) AS dc
CROSS APPLY (SELECT CHARINDEX(' ', dc.DIA_CHI) AS VI_TRI_DAU_CACH,
                    CHARINDEX(',', dc.DIA_CHI) AS VI_TRI_DAU_PHAY) AS vt
WHERE nv.MANV IN
(
    SELECT MA_NVIEN
    FROM dbo.THANNHAN
    GROUP BY MA_NVIEN
    HAVING COUNT(*) > 2
)
ORDER BY nv.MANV;

;WITH SoNhanVien AS
(
    SELECT pb.MAPHG, pb.TENPHG, pb.TRPHG, COUNT(nv.MANV) AS SO_NHAN_VIEN
    FROM dbo.PHONGBAN AS pb
    LEFT JOIN dbo.NHANVIEN AS nv ON nv.PHG = pb.MAPHG
    GROUP BY pb.MAPHG, pb.TENPHG, pb.TRPHG
)
SELECT pb.TENPHG,
       CONCAT(tp.HONV, N' ', tp.TENLOT, N' ', tp.TENNV) AS HO_TEN_TRUONG_PHONG,
       CONCAT(tp.HONV, N' ', tp.TENLOT, N' ', REPLACE(tp.TENNV, tp.TENNV, N'Fpoly')) AS HO_TEN_THAY_THE,
       pb.SO_NHAN_VIEN
FROM SoNhanVien AS pb
LEFT JOIN dbo.NHANVIEN AS tp ON tp.MANV = pb.TRPHG
WHERE pb.SO_NHAN_VIEN = (SELECT MAX(SO_NHAN_VIEN) FROM SoNhanVien)
ORDER BY pb.MAPHG;

SELECT MANV, HONV, TENLOT, TENNV, NGSINH
FROM dbo.NHANVIEN
WHERE YEAR(NGSINH) BETWEEN 1960 AND 1965
ORDER BY MANV;

DECLARE @HomNay DATE = CAST(GETDATE() AS DATE);

SELECT MANV, HONV, TENLOT, TENNV, NGSINH,
       DATEDIFF(YEAR, NGSINH, @HomNay)
       - CASE WHEN DATEADD(YEAR, DATEDIFF(YEAR, NGSINH, @HomNay), NGSINH) > @HomNay
              THEN 1 ELSE 0 END AS TUOI
FROM dbo.NHANVIEN
ORDER BY MANV;

SELECT MANV, HONV, TENLOT, TENNV, NGSINH,
       CHOOSE(((DATEDIFF(DAY, CONVERT(DATE, '19000101', 112), NGSINH) % 7 + 7) % 7) + 1,
              N'Thứ hai', N'Thứ ba', N'Thứ tư', N'Thứ năm', N'Thứ sáu', N'Thứ bảy', N'Chủ nhật') AS THU_SINH
FROM dbo.NHANVIEN
ORDER BY MANV;

;WITH SoNhanVien AS
(
    SELECT PHG, COUNT(*) AS SO_NHAN_VIEN
    FROM dbo.NHANVIEN
    GROUP BY PHG
)
SELECT pb.TENPHG,
       COALESCE(sl.SO_NHAN_VIEN, 0) AS SO_NHAN_VIEN,
       CONCAT(tp.HONV, N' ', tp.TENLOT, N' ', tp.TENNV) AS HO_TEN_TRUONG_PHONG,
       pb.NG_NHANCHUC,
       CONVERT(VARCHAR(10), pb.NG_NHANCHUC, 105) AS NGAY_NHAN_CHUC_DD_MM_YYYY,
       CONVERT(VARCHAR(8), pb.NG_NHANCHUC, 5) AS NGAY_NHAN_CHUC_DD_MM_YY
FROM dbo.PHONGBAN AS pb
LEFT JOIN SoNhanVien AS sl ON sl.PHG = pb.MAPHG
LEFT JOIN dbo.NHANVIEN AS tp ON tp.MANV = pb.TRPHG
ORDER BY pb.MAPHG;
